import { useState } from 'react';
import { Command, RiskLevel } from '@/types/terminal';
import { Card } from '@/components/ui/card';
import { Button } from '@/components/ui/button';
import { Badge } from '@/components/ui/badge';
import { Separator } from '@/components/ui/separator';
import { Copy, Trash2, ChevronDown, ChevronUp, Clock, Terminal, AlertTriangle, ShieldCheck, ShieldAlert, Info, FlaskConical } from 'lucide-react';

interface CommandOutputProps {
  command: Command;
  onCopy: (text: string) => void;
  onDelete: (id: string) => void;
}

export function CommandOutput({ command, onCopy, onDelete }: CommandOutputProps) {
  const [isExpanded, setIsExpanded] = useState(true);

  const riskColor: Record<RiskLevel, string> = {
    low: 'text-primary',
    medium: 'text-accent',
    high: 'text-destructive',
  };

  const getRiskBadge = (risk: RiskLevel) => {
    if (risk === 'high') {
      return (
        <Badge variant="destructive" className="bg-destructive/20 text-destructive border-destructive/30">
          <ShieldAlert className="h-3 w-3 mr-1" />
          High risk
        </Badge>
      );
    }
    if (risk === 'medium') {
      return (
        <Badge variant="secondary" className="bg-accent/20 text-accent border-accent/30">
          <AlertTriangle className="h-3 w-3 mr-1" />
          Changes things
        </Badge>
      );
    }
    return (
      <Badge variant="default" className="bg-primary/20 text-primary border-primary/30">
        <ShieldCheck className="h-3 w-3 mr-1" />
        Read-only
      </Badge>
    );
  };

  const getShellIcon = (shell: string) => {
    const icons = {
      powershell: '🔷',
      cmd: '⬛',
      bash: '🐧',
      termux: '📱'
    };
    return icons[shell as keyof typeof icons] || '💻';
  };

  return (
    <Card className="bg-card/30 backdrop-blur-sm border-border/50">
      <div className="p-3 md:p-4">
        {/* Header */}
        <div className="flex items-center justify-between mb-3">
          <div className="flex items-center gap-2 flex-wrap">
            <span className="text-lg">{getShellIcon(command.shell)}</span>
            <div className="flex items-center gap-2 text-xs md:text-sm text-muted-foreground">
              <Clock className="h-3 w-3" />
              <span className="hidden sm:inline">{command.timestamp.toLocaleString()}</span>
              <span className="sm:hidden">{command.timestamp.toLocaleTimeString()}</span>
            </div>
            {command.command && getRiskBadge(command.risk)}
            {command.source === 'demo' && (
              <Badge variant="outline" className="text-muted-foreground" title="Generated by the offline keyword demo, not the AI">
                <FlaskConical className="h-3 w-3 mr-1" />
                Demo
              </Badge>
            )}
          </div>
          
          <div className="flex items-center gap-1 md:gap-2">
            <Button
              variant="ghost"
              size="sm"
              onClick={() => setIsExpanded(!isExpanded)}
              aria-label={isExpanded ? 'Collapse' : 'Expand'}
              className="text-muted-foreground hover:text-foreground p-1 md:p-2"
            >
              {isExpanded ? (
                <ChevronUp className="h-4 w-4" />
              ) : (
                <ChevronDown className="h-4 w-4" />
              )}
            </Button>
            <Button
              variant="ghost"
              size="sm"
              onClick={() => onDelete(command.id)}
              aria-label="Delete from history"
              className="text-muted-foreground hover:text-destructive p-1 md:p-2"
            >
              <Trash2 className="h-4 w-4" />
            </Button>
          </div>
        </div>

        {/* Prompt */}
        <div className="mb-3">
          <div className="text-sm text-muted-foreground mb-1">Prompt:</div>
          <div className="text-sm bg-secondary/30 rounded p-2 border border-border/30">
            {command.prompt}
          </div>
        </div>

        {isExpanded && (
          <>
            <Separator className="my-3" />
            
            {command.command ? (
              <>
                {/* Generated Command */}
                <div className="mb-4">
                  <div className="flex items-center gap-2 mb-2">
                    <Terminal className="h-4 w-4 text-primary" />
                    <span className="text-sm font-medium">Command</span>
                  </div>
                  <div className="bg-background/80 rounded-lg p-3 border border-border/50 font-mono text-sm">
                    <div className="flex items-start justify-between gap-2">
                      <code className={`flex-1 break-all whitespace-pre-wrap ${riskColor[command.risk]}`}>
                        {command.command}
                      </code>
                      <Button
                        variant="ghost"
                        size="sm"
                        onClick={() => onCopy(command.command)}
                        className="shrink-0 opacity-80 hover:opacity-100"
                      >
                        <Copy className="h-3 w-3 mr-1" />
                        Copy
                      </Button>
                    </div>
                  </div>
                </div>

                {/* What it does */}
                {command.explanation && (
                  <div className="mb-3 flex gap-2 text-sm text-foreground/90">
                    <Info className="h-4 w-4 mt-0.5 shrink-0 text-muted-foreground" />
                    <p>{command.explanation}</p>
                  </div>
                )}

                {/* Before you run it */}
                {command.caveat && (
                  <div
                    className={`flex gap-2 rounded-lg border p-3 text-sm ${
                      command.risk === 'high'
                        ? 'border-destructive/40 bg-destructive/10 text-destructive'
                        : 'border-accent/40 bg-accent/10'
                    }`}
                  >
                    <AlertTriangle className="h-4 w-4 mt-0.5 shrink-0" />
                    <p>{command.caveat}</p>
                  </div>
                )}

                <p className="mt-3 text-xs text-muted-foreground">
                  TermiAI never runs commands. Copy it into your {command.shell === 'cmd' ? 'Command Prompt' : command.shell === 'powershell' ? 'PowerShell' : command.shell === 'termux' ? 'Termux' : 'terminal'} and review it before pressing Enter.
                </p>
              </>
            ) : (
              <div className="flex gap-2 text-sm text-foreground/90">
                <Info className="h-4 w-4 mt-0.5 shrink-0 text-muted-foreground" />
                <p>{command.explanation || 'No command was generated for this request.'}</p>
              </div>
            )}
          </>
        )}
      </div>
    </Card>
  );
}